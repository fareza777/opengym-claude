//
// Register: informal "kamu", the way Indonesian lifters actually talk and the way
// every app in this category is written locally. "Anda" would read like a bank.
//
// Two vocabulary decisions worth stating, because English collapses them and
// Indonesian does not:
//   workout  → "latihan"  (one session)
//   exercise → "gerakan"  (one movement)
// Translating both as "latihan" is the common shortcut and it makes half the
// screens ambiguous — "tambah latihan" would mean either "add a session" or "add
// a movement". Keeping them apart costs nothing and removes the ambiguity.
//
// Lifting jargon that Indonesian gyms already use in English is left in English
// on purpose: set, rep, superset, deload, PR, streak, cardio, RIR, RPE. A
// translated "deload" helps nobody.
